#!/usr/bin/env bash
set -euo pipefail

etc_root="/etc"
dry_run=0
rpm_command="/usr/bin/rpm"
cmp_command="/usr/bin/cmp"
rm_command="/usr/bin/rm"

usage() {
	cat <<'USAGE'
Usage: migrate-legacy-config [--dry-run] [--etc-root PATH]

Remove obsolete /etc shadows created by older Galaxy Book OV02C10 installers.
A file is removed only when it is an unowned regular file whose bytes exactly
match a configuration generated by this project. Package-owned files, symlinks,
and locally customized files are always preserved.
USAGE
}

fail() {
	printf 'galaxybook-ov02c10: %s\n' "$*" >&2
	return 1
}

migrate_file() {
	local relative_path="$1"
	local expected_content="$2"
	local target="${etc_root}/${relative_path}"

	if [[ ! -e "$target" && ! -L "$target" ]]; then
		return 0
	fi

	if [[ -L "$target" || ! -f "$target" ]]; then
		printf 'Preserving non-regular legacy path: %s\n' "$target"
		return 0
	fi

	if "$rpm_command" -qf -- "$target" >/dev/null 2>&1; then
		printf 'Preserving package-owned configuration: %s\n' "$target"
		return 0
	fi

	if ! "$cmp_command" -s -- "$target" <(printf '%s' "$expected_content"); then
		printf 'Preserving customized configuration: %s\n' "$target"
		return 0
	fi

	if [[ "$dry_run" -eq 1 ]]; then
		printf 'Would remove exact legacy configuration: %s\n' "$target"
		return 0
	fi

	printf 'Removing exact legacy configuration: %s\n' "$target"
	if ! "$rm_command" -- "$target"; then
		fail "could not remove exact legacy configuration: ${target}"
		return 1
	fi
}

main() {
	while [[ $# -gt 0 ]]; do
		case "$1" in
			--dry-run)
				dry_run=1
				shift
				;;
			--etc-root)
				if [[ $# -lt 2 ]]; then
					fail "missing value for --etc-root"
					return 2
				fi
				etc_root="${2%/}"
				shift 2
				;;
			-h|--help)
				usage
				return 0
				;;
			*)
				fail "unknown argument: $1"
				usage >&2
				return 2
				;;
		esac
	done

	if [[ -z "$etc_root" || ! -d "$etc_root" ]]; then
		fail "configuration root not found: ${etc_root}"
		return 1
	fi

	if [[ "$etc_root" == "/etc" && "$EUID" -ne 0 ]]; then
		fail "legacy configuration migration must run as root"
		return 1
	fi

	migrate_file "modules-load.d/galaxybook-ov02c10.conf" $'ov02c10\n' || return 1
	migrate_file "modprobe.d/galaxybook-ov02c10.conf" \
		$'softdep intel_ipu6_isys pre: ov02c10\n' || return 1
	migrate_file "depmod.d/galaxybook-ov02c10.conf" \
		$'override ov02c10 * extra/galaxybook-ov02c10/drivers/media/i2c\n' || return 1
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
	main "$@"
fi
